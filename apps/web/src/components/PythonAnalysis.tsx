
import type { AnalysisResult } from "@/types/analysis";

interface PythonAnalysisProps {
  analysis: AnalysisResult;
}

function formatNumber(value: number): string {
  if (!Number.isFinite(value)) {
    return "N/A";
  }

  return value.toLocaleString(undefined, {
    maximumFractionDigits: 3,
  });
}

export default function PythonAnalysis({
  analysis,
}: PythonAnalysisProps) {
  const numericColumns = Object.entries(
    analysis.numeric_columns
  );

  const missingColumns = Object.entries(
    analysis.missing_by_column
  ).filter(([, count]) => count > 0);

  return (
    <section className="rounded-xl border border-slate-800 bg-slate-900 p-6">
      <div className="mb-6">
        <p className="text-sm font-medium text-blue-400">
          Python / pandas
        </p>

        <h2 className="mt-2 text-xl font-semibold text-white">
          Statistical Analysis
        </h2>

        <p className="mt-2 text-sm text-slate-400">
          Analysis results generated by the local Python API.
        </p>
      </div>

      <div className="grid grid-cols-1 gap-4 sm:grid-cols-3">
        <div className="rounded-lg bg-slate-950 p-4">
          <p className="text-sm text-slate-400">
            Rows
          </p>
          <p className="mt-2 text-2xl font-bold">
            {analysis.rows.toLocaleString()}
          </p>
        </div>

        <div className="rounded-lg bg-slate-950 p-4">
          <p className="text-sm text-slate-400">
            Columns
          </p>
          <p className="mt-2 text-2xl font-bold">
            {analysis.columns.toLocaleString()}
          </p>
        </div>

        <div className="rounded-lg bg-slate-950 p-4">
          <p className="text-sm text-slate-400">
            Missing Values
          </p>
          <p className="mt-2 text-2xl font-bold">
            {analysis.missing_values.toLocaleString()}
          </p>
        </div>
      </div>

      <div className="mt-8">
        <h3 className="mb-4 text-lg font-semibold">
          Numeric Column Statistics
        </h3>

        {numericColumns.length === 0 ? (
          <p className="text-sm text-slate-400">
            No numeric columns found.
          </p>
        ) : (
          <div className="overflow-x-auto">
            <table className="w-full text-left text-sm">
              <thead className="border-b border-slate-700 text-slate-400">
                <tr>
                  <th className="px-3 py-3">Column</th>
                  <th className="px-3 py-3">Count</th>
                  <th className="px-3 py-3">Mean</th>
                  <th className="px-3 py-3">Median</th>
                  <th className="px-3 py-3">Std</th>
                  <th className="px-3 py-3">Min</th>
                  <th className="px-3 py-3">Max</th>
                </tr>
              </thead>

              <tbody>
                {numericColumns.map(([name, stats]) => (
                  <tr
                    key={name}
                    className="border-b border-slate-800"
                  >
                    <td className="px-3 py-3 font-medium">
                      {name}
                    </td>
                    <td className="px-3 py-3">
                      {formatNumber(stats.count)}
                    </td>
                    <td className="px-3 py-3">
                      {formatNumber(stats.mean)}
                    </td>
                    <td className="px-3 py-3">
                      {formatNumber(stats.median)}
                    </td>
                    <td className="px-3 py-3">
                      {formatNumber(stats.std)}
                    </td>
                    <td className="px-3 py-3">
                      {formatNumber(stats.min)}
                    </td>
                    <td className="px-3 py-3">
                      {formatNumber(stats.max)}
                    </td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        )}
      </div>

      <div className="mt-8">
        <h3 className="mb-4 text-lg font-semibold">
          Missing Values by Column
        </h3>

        {missingColumns.length === 0 ? (
          <p className="text-sm text-emerald-400">
            No missing values detected.
          </p>
        ) : (
          <div className="space-y-3">
            {missingColumns.map(([name, count]) => (
              <div
                key={name}
                className="flex items-center justify-between rounded-lg bg-slate-950 px-4 py-3"
              >
                <span className="text-sm text-slate-300">
                  {name}
                </span>
                <span className="font-semibold text-amber-400">
                  {count.toLocaleString()}
                </span>
              </div>
            ))}
          </div>
        )}
      </div>
    </section>
  );
}
